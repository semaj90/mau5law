-- Week 3: Knowledge Base Fixing Tables
-- Migration: Add auto_approval_rules and kb_provenance_graph tables

-- Table 1: Auto-Approval Rules (Task 3.2)
-- Stores patterns for trusted knowledge sources that can bypass human validation
CREATE TABLE IF NOT EXISTS auto_approval_rules (
    rule_id SERIAL PRIMARY KEY,
    source_pattern VARCHAR(255) NOT NULL,
    source_type VARCHAR(50) NOT NULL, -- 'qdrant', 'couchdb', 'github', etc.
    min_relevance_score REAL DEFAULT 0.8,
    auto_approve BOOLEAN DEFAULT true,
    description TEXT,
    created_by VARCHAR(100),
    created_at TIMESTAMP DEFAULT NOW(),
    updated_at TIMESTAMP DEFAULT NOW(),
    is_active BOOLEAN DEFAULT true,

    -- Constraints
    CONSTRAINT unique_pattern_type UNIQUE(source_pattern, source_type)
);

-- Index for fast pattern matching
CREATE INDEX IF NOT EXISTS idx_auto_approval_active
ON auto_approval_rules(source_type, is_active)
WHERE is_active = true;

-- Table 2: KB Provenance Graph (Task 3.3)
-- Full audit trail linking fixes to validated knowledge sources
CREATE TABLE IF NOT EXISTS kb_provenance_graph (
    fix_id VARCHAR(50) PRIMARY KEY,
    file_path TEXT NOT NULL,
    error_type VARCHAR(50),
    error_message TEXT,

    -- Fix details
    original_code TEXT,
    fixed_code TEXT,
    explanation TEXT,

    -- Provenance
    validated_sources JSONB NOT NULL, -- Array of source objects with IDs
    source_citations TEXT[], -- Array of source IDs used
    confidence_score REAL,

    -- LLM details
    llm_provider VARCHAR(100),
    llm_model VARCHAR(100),
    generation_time_ms INTEGER,

    -- Application tracking
    applied_at TIMESTAMP NOT NULL DEFAULT NOW(),
    applied_by VARCHAR(100) DEFAULT 'system',
    user_approved BOOLEAN DEFAULT true,
    application_notes TEXT,

    -- Status
    success BOOLEAN DEFAULT true,
    error_message TEXT,
    reverted_at TIMESTAMP,
    reverted_by VARCHAR(100),

    -- Metadata
    created_at TIMESTAMP DEFAULT NOW(),
    updated_at TIMESTAMP DEFAULT NOW()
);

-- Indexes for fast queries
CREATE INDEX IF NOT EXISTS idx_kb_provenance_file
ON kb_provenance_graph(file_path);

CREATE INDEX IF NOT EXISTS idx_kb_provenance_applied_at
ON kb_provenance_graph(applied_at DESC);

CREATE INDEX IF NOT EXISTS idx_kb_provenance_success
ON kb_provenance_graph(success);

CREATE INDEX IF NOT EXISTS idx_kb_provenance_error_type
ON kb_provenance_graph(error_type);

-- GIN index for JSONB source queries
CREATE INDEX IF NOT EXISTS idx_kb_provenance_sources
ON kb_provenance_graph USING GIN(validated_sources);

-- Table 3: Error Sessions (migrate from in-memory)
-- Stores active error fixing sessions
CREATE TABLE IF NOT EXISTS error_sessions (
    session_id VARCHAR(50) PRIMARY KEY,
    error_context JSONB NOT NULL,
    search_results JSONB, -- Sources found
    validated_sources TEXT[], -- User-approved source IDs
    rejected_sources TEXT[], -- User-rejected source IDs
    validation_notes TEXT,

    -- Status
    status VARCHAR(50) DEFAULT 'searching', -- 'searching', 'validating', 'generating', 'applied', 'failed'

    -- Timestamps
    created_at TIMESTAMP DEFAULT NOW(),
    updated_at TIMESTAMP DEFAULT NOW(),
    expires_at TIMESTAMP DEFAULT NOW() + INTERVAL '24 hours'
);

-- Index for cleanup of expired sessions
CREATE INDEX IF NOT EXISTS idx_error_sessions_expires
ON error_sessions(expires_at);

-- Table 4: Generated Fixes (migrate from in-memory)
-- Stores all fixes generated by LLM (applied or not)
CREATE TABLE IF NOT EXISTS generated_fixes (
    fix_id VARCHAR(50) PRIMARY KEY,
    session_id VARCHAR(50) REFERENCES error_sessions(session_id) ON DELETE CASCADE,

    -- Fix content
    original_code TEXT,
    fixed_code TEXT NOT NULL,
    explanation TEXT,

    -- Source tracking
    source_citations TEXT[],
    confidence_score REAL,

    -- LLM details
    llm_provider VARCHAR(100),
    llm_model VARCHAR(100),
    generation_time_ms INTEGER,

    -- Status
    applied BOOLEAN DEFAULT false,
    applied_at TIMESTAMP,

    -- Timestamps
    created_at TIMESTAMP DEFAULT NOW()
);

-- Index for fast session lookups
CREATE INDEX IF NOT EXISTS idx_generated_fixes_session
ON generated_fixes(session_id);

-- View: Fix Success Rate by Error Type
CREATE OR REPLACE VIEW fix_success_rate_by_error AS
SELECT
    error_type,
    COUNT(*) as total_fixes,
    SUM(CASE WHEN success THEN 1 ELSE 0 END) as successful_fixes,
    ROUND(AVG(CASE WHEN success THEN 1.0 ELSE 0.0 END) * 100, 2) as success_rate_pct,
    ROUND(AVG(confidence_score), 3) as avg_confidence
FROM kb_provenance_graph
WHERE applied_at >= NOW() - INTERVAL '30 days'
GROUP BY error_type
ORDER BY total_fixes DESC;

-- View: Most Effective Sources
CREATE OR REPLACE VIEW most_effective_sources AS
WITH source_usage AS (
    SELECT
        jsonb_array_elements_text(validated_sources::jsonb -> 'source_id') as source_id,
        success,
        confidence_score
    FROM kb_provenance_graph
    WHERE applied_at >= NOW() - INTERVAL '30 days'
)
SELECT
    source_id,
    COUNT(*) as times_used,
    SUM(CASE WHEN success THEN 1 ELSE 0 END) as successful_uses,
    ROUND(AVG(CASE WHEN success THEN 1.0 ELSE 0.0 END) * 100, 2) as success_rate_pct,
    ROUND(AVG(confidence_score), 3) as avg_confidence
FROM source_usage
GROUP BY source_id
HAVING COUNT(*) >= 3
ORDER BY success_rate_pct DESC, times_used DESC
LIMIT 50;

-- View: Auto-Approval Effectiveness
CREATE OR REPLACE VIEW auto_approval_effectiveness AS
SELECT
    ar.source_pattern,
    ar.source_type,
    ar.min_relevance_score,
    COUNT(kg.fix_id) as fixes_applied,
    SUM(CASE WHEN kg.success THEN 1 ELSE 0 END) as successful_fixes,
    ROUND(AVG(CASE WHEN kg.success THEN 1.0 ELSE 0.0 END) * 100, 2) as success_rate_pct
FROM auto_approval_rules ar
LEFT JOIN kb_provenance_graph kg
    ON kg.validated_sources::jsonb @> jsonb_build_array(jsonb_build_object('source_id', ar.source_pattern))
WHERE ar.is_active = true
    AND kg.applied_at >= NOW() - INTERVAL '30 days'
GROUP BY ar.rule_id, ar.source_pattern, ar.source_type, ar.min_relevance_score
ORDER BY fixes_applied DESC;

-- Function: Clean up expired error sessions
CREATE OR REPLACE FUNCTION cleanup_expired_sessions()
RETURNS INTEGER AS $$
DECLARE
    deleted_count INTEGER;
BEGIN
    DELETE FROM error_sessions
    WHERE expires_at < NOW()
        AND status NOT IN ('applied', 'generating');

    GET DIAGNOSTICS deleted_count = ROW_COUNT;
    RETURN deleted_count;
END;
$$ LANGUAGE plpgsql;

-- Function: Get fix provenance chain
CREATE OR REPLACE FUNCTION get_fix_provenance_chain(p_file_path TEXT)
RETURNS TABLE (
    fix_id VARCHAR,
    applied_at TIMESTAMP,
    error_type VARCHAR,
    success BOOLEAN,
    confidence_score REAL,
    source_count INTEGER,
    llm_provider VARCHAR
) AS $$
BEGIN
    RETURN QUERY
    SELECT
        kg.fix_id,
        kg.applied_at,
        kg.error_type,
        kg.success,
        kg.confidence_score,
        jsonb_array_length(kg.validated_sources) as source_count,
        kg.llm_provider
    FROM kb_provenance_graph kg
    WHERE kg.file_path = p_file_path
    ORDER BY kg.applied_at DESC;
END;
$$ LANGUAGE plpgsql;

